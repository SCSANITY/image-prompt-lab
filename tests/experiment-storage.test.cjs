test('verified migration changes persistent roots, rewrites locators and preserves all input originals', async t => {
  const f = await fixture(t); const r = await f.add()
  const plan = await f.storage.prepareMigration(f.destination)
  const moved = await f.storage.migrate(plan.token)
  assert.equal(moved.retainedFiles, 0)
  const newFile = path.join(moved.outputRoot, r.name, 'output-01.png')
  assert.deepEqual(await fs.readFile(newFile), r.data)
  assert.equal(await exists(r.file), false)
  assert.equal(await exists(r.directory), false)
  assert.equal(await exists(f.input), true)
  const locator = JSON.parse(await fs.readFile(path.join(moved.evidenceRoot, r.name, 'local-history.json')))
  assert.equal(locator.output_directory, path.dirname(newFile))
  const restarted = createExperimentStorage(f)
  assert.deepEqual(await restarted.init(), { evidenceRoot: moved.evidenceRoot, outputRoot: moved.outputRoot })
  assert.equal((await restarted.status()).runCount, 1)
})
