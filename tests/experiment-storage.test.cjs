test('an image removal failure keeps metadata and can be retried with a fresh confirmation', async t => {
  let fail = true
  const f = await fixture(t, { unlink: async p => { if (fail && p.endsWith('.png')) throw Error('synthetic locked file'); return fs.unlink(p) } })
  const r = await f.add()
  const plan = await f.storage.prepareDelete(r.runId)
  const result = await f.storage.deleteRun(plan.token, true)
  assert.equal(result.deleted, false); assert.equal(result.removedBytes, 0)
  assert.equal((await f.storage.status()).runCount, 1)
  fail = false
  assert.equal((await f.storage.deleteRun((await f.storage.prepareDelete(r.runId)).token, true)).deleted, true)
  assert.equal(await exists(f.input), true)
})

test('partial metadata deletion is restored on failure, retaining history and original images', async t => {
  const f = await fixture(t, { unlink: async p => { if (p.endsWith('local-inputs.json')) throw Error('synthetic locked metadata'); return fs.unlink(p) } })
  const r = await f.add()
  const before = await Promise.all((await fs.readdir(r.directory)).map(async name => [name, await fs.readFile(path.join(r.directory, name), 'utf8')]))
  const result = await f.storage.deleteRun((await f.storage.prepareDelete(r.runId)).token, false)
  assert.equal(result.deleted, false); assert.equal(result.removedBytes, 0)
  for (const [name, content] of before) assert.equal(await fs.readFile(path.join(r.directory, name), 'utf8'), content)
  assert.equal((await f.storage.status()).runCount, 1)
  assert.deepEqual(await fs.readFile(r.file), r.data)
})

