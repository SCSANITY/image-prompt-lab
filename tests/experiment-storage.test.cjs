test('tokens cannot be forged and storage operations cannot overlap generation', async t => {
  const f = await fixture(t); const r = await f.add()
  await assert.rejects(() => f.storage.deleteRun('forged', true), /expired/)
  const plan = await f.storage.prepareDelete(r.runId)
  let release
  const task = f.storage.exclusive(() => new Promise(resolve => { release = resolve }))
  await assert.rejects(() => f.storage.deleteRun(plan.token, true), /finish/)
  release(); await task
  assert.equal((await f.storage.deleteRun(plan.token, false)).deleted, true)
})
