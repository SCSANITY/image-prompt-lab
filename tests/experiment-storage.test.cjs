'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const crypto = require('node:crypto')
const { createExperimentStorage } = require('../electron/experimentStorage.cjs')

async function fixture(t, options = {}) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'prompt-lab-storage-test-'))
  t.after(async () => {
    assert.equal(path.dirname(root), os.tmpdir())
    await fs.rm(root, { recursive: true, force: true })
  })
  const profileRoot = path.join(root, 'profile')
  const defaultOutputRoot = path.join(root, 'outputs')
  const destination = path.join(root, 'new-drive')
  await fs.mkdir(profileRoot); await fs.mkdir(defaultOutputRoot); await fs.mkdir(destination)
  const input = path.join(root, 'source-original.png')
  await fs.writeFile(input, 'synthetic original; never delete')
  const storage = createExperimentStorage({ profileRoot, defaultOutputRoot, ...options })
  await storage.init()
  async function add(runId = 'run_1', inputs = [input]) {
    const name = `${runId}_synthetic`
    const directory = path.join(storage.roots().evidenceRoot, name)
    const images = path.join(defaultOutputRoot, name)
    await fs.mkdir(directory, { recursive: true }); await fs.mkdir(images)
    const data = Buffer.from(`synthetic generated bytes ${runId}`)
    const file = path.join(images, 'output-01.png')
    await fs.writeFile(file, data)
    const output = { file: 'output-01.png', byte_count: data.length, sha256: crypto.createHash('sha256').update(data).digest('hex') }
    const records = {
      'request.json': { run_id: runId, experiment_name: runId, prompt: 'Synthetic test only' },
      'evidence.json': { run_id: runId, outputs: [output], partial_outputs: [] },
      'local-inputs.json': { images: inputs.map(p => ({ path: p })) },
      'local-history.json': { schema_version: 1, run_id: runId, output_directory: images },
    }
    for (const [name, value] of Object.entries(records)) await fs.writeFile(path.join(directory, name), JSON.stringify(value))
    return { runId, name, directory, images, file, data, output }
  }
  return { root, profileRoot, defaultOutputRoot, destination, input, storage, add }
}
const exists = async p => { try { await fs.access(p); return true } catch { return false } }

test('record-only deletion frees measured metadata but keeps output and source files', async t => {
  const f = await fixture(t); const r = await f.add()
  const plan = await f.storage.prepareDelete(r.runId)
  assert.ok(plan.recordBytes > 0); assert.equal(plan.imageBytes, r.data.length)
  const result = await f.storage.deleteRun(plan.token, false)
  assert.equal(result.deleted, true); assert.equal(result.removedBytes, plan.recordBytes)
  assert.equal(await exists(r.directory), false)
  assert.deepEqual(await fs.readFile(r.file), r.data)
  assert.equal(await exists(f.input), true)
})
test('record-plus-images removes only verified run files and leaves unrelated files/originals', async t => {
  const f = await fixture(t); const r = await f.add()
  await fs.writeFile(path.join(r.images, 'keep-my-note.txt'), 'unrelated user file')
  const plan = await f.storage.prepareDelete(r.runId)
  const result = await f.storage.deleteRun(plan.token, true)
  assert.equal(result.deleted, true)
  assert.equal(result.removedBytes, plan.recordBytes + plan.reclaimableImageBytes)
  assert.equal(await exists(r.file), false)
  assert.equal(await exists(path.join(r.images, 'keep-my-note.txt')), true)
  assert.equal(await exists(f.input), true)
  await assert.rejects(() => f.storage.deleteRun(plan.token, true), /expired/)
})
